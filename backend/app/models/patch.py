from typing import Optional

from pydantic import BaseModel, Field


class PatchEdit(BaseModel):
    file: str
    old: str = Field(min_length=1)
    new: str


class PatchProposal(BaseModel):
    explanation: str
    edits: list[PatchEdit] = Field(min_length=1, max_length=3)
    diff: str = ""  # unified diff, generated by our code (not by the LLM)


class RunReport(BaseModel):
    """What one sandbox run of the checks found."""

    mode: str  # docker | local
    compiled: bool = False
    tests_passed: int = 0
    tests_failed: int = 0
    replay_statuses: list[int] = Field(default_factory=list)
    replay_error: Optional[str] = None
    lint_issues: Optional[int] = None
    timed_out: bool = False
    output_tail: str = ""

    @property
    def replay_crashed(self) -> bool:
        """An unhandled server error. 502/503/504 are deliberate 'service unavailable' answers."""
        return any(s >= 500 and s not in (502, 503, 504) for s in self.replay_statuses)


class ValidationResult(BaseModel):
    passed: bool
    mode: str
    reason: str
    bug_reproduced: bool
    baseline: RunReport  # the original, unpatched code
    patched: RunReport
    warnings: list[str] = Field(default_factory=list)  # filled in by the patch review

    @property
    def accepted(self) -> bool:
        """Passed the sandbox AND the review found nothing suspicious."""
        return self.passed and not self.warnings
